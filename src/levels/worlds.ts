export function getLevel(id: LevelId): LevelDef {
  const { world, stage } = parseLevelId(id);
  const theme = worldTheme(world);
  const compiled = COURSES[id];
  return {
    id,
    world,
    stage,
    theme,
    name: NAMES[id],
    rows: compiled.rows,
    course: compiled,
    isCastle: stage === 4,
  };
}


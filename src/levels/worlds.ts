import { parseLevelId, type LevelId, type Theme, worldBossKind } from '../config';
import { compileCourse, LEDGE, type CompiledCourse, type CourseSpec } from './grid';

const { hop, low, mid, high } = LEDGE;

/** Ledge values are tiles above the floor. A full jump reaches `low`; `mid`/`high` need steps. */

export interface LevelDef {
  id: LevelId;
  world: number;
  stage: number;
  theme: Theme;
  name: string;
  rows: string[];
  course: CompiledCourse;
  isCastle: boolean;
}

function worldTheme(world: number): Theme {
  switch (world) {
    case 1:
      return 'grass';
    case 2:
      return 'snow';
    case 3:
      return 'desert';
    case 4:
      return 'ocean';
    case 5:
      return 'castle';
    case 6:
      return 'rainforest';
    default:
      return 'grass';
  }
}

function course(world: number, stage: number, spec: CourseSpec): CompiledCourse {
  return compileCourse(world, stage, spec, worldTheme(world));
}


export function getLevel(id: LevelId): LevelDef {
  const { world, stage } = parseLevelId(id);
  const theme = worldTheme(world);
  return {
    id,
    world,
    stage,
    theme,
    name: NAMES[id],
    rows: COURSES[id],
    isCastle: stage === 4,
  };
}

export function getWorldBossKind(world: number) {
  return worldBossKind(world);
}
